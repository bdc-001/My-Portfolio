import fs from "node:fs";
import path from "node:path";

const WORDS_PER_MINUTE = 230;
const SITE = "https://keephustling.in";

const unquote = (value) => value.replace(/^(["'])(.*)\1$/, "$2");

const parseValue = (raw) => {
  const value = raw.trim();
  if (value === "true" || value === "false") return value === "true";
  if (value.startsWith("[") && value.endsWith("]")) {
    return value
      .slice(1, -1)
      .split(",")
      .map((item) => unquote(item.trim()))
      .filter(Boolean);
  }
  return unquote(value);
};

/** Splits a post into its `---` frontmatter (a small YAML subset) and markdown body. */
export function parsePost(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) return { meta: {}, body: source.trim() };

  const meta = {};
  let listKey = null;
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && listKey) {
      meta[listKey].push(unquote(item[1].trim()));
      continue;
    }
    const pair = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!pair) continue;
    const [, key, raw] = pair;
    if (raw.trim() === "") {
      meta[key] = [];
      listKey = key;
    } else {
      meta[key] = parseValue(raw);
      listKey = null;
    }
  }
  return { meta, body: match[2].trim() };
}

const readingTime = (body) => {
  const words = body.replace(/!\[[^\]]*\]\([^)]*\)/g, "").split(/\s+/).filter(Boolean).length;
  return { words, readTime: `${Math.max(1, Math.round(words / WORDS_PER_MINUTE))} min read` };
};

const postFile = (id) => id.split("?")[0];

/**
 * Blog posts live in `src/content/blog/<slug>/index.md` next to their images.
 * `index.md?meta` resolves to the frontmatter only (eagerly bundled for listings);
 * `index.md?body` resolves to the markdown body (lazy, one chunk per post).
 * Also keeps the API's slug allow-list and the sitemap's blog URLs in sync.
 */
export default function blogContent({ contentDir = "src/content/blog" } = {}) {
  let root = process.cwd();
  let isBuild = false;

  const listPosts = () => {
    const dir = path.resolve(root, contentDir);
    if (!fs.existsSync(dir)) return [];
    return fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(dir, entry.name, "index.md")))
      .map((entry) => {
        const { meta } = parsePost(fs.readFileSync(path.join(dir, entry.name, "index.md"), "utf8"));
        return { slug: entry.name, date: String(meta.date ?? ""), draft: meta.draft === true };
      })
      .filter((post) => !(isBuild && post.draft))
      .sort((a, b) => b.date.localeCompare(a.date));
  };

  const writeIfChanged = (file, contents) => {
    if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === contents) return;
    fs.writeFileSync(file, contents);
  };

  const syncManifests = () => {
    const posts = listPosts();

    writeIfChanged(
      path.resolve(root, "server/blogSlugs.js"),
      `// Generated by scripts/vite-plugin-blog.js from ${contentDir}. Do not edit by hand.\nexport const BLOG_SLUGS = ${JSON.stringify(
        posts.map((post) => post.slug),
        null,
        2
      )};\n`
    );

    const sitemapPath = path.resolve(root, "public/sitemap.xml");
    if (fs.existsSync(sitemapPath)) {
      const sitemap = fs.readFileSync(sitemapPath, "utf8");
      const withoutPosts = sitemap.replace(new RegExp(`\\s*<url><loc>${SITE}/blog/[^<]+</loc>.*?</url>`, "g"), "");
      const entries = posts
        .map(
          (post) =>
            `\n  <url><loc>${SITE}/blog/${post.slug}</loc><lastmod>${post.date}</lastmod><changefreq>monthly</changefreq><priority>0.8</priority></url>`
        )
        .join("");
      const next = withoutPosts.replace(/(<url><loc>[^<]+\/blog<\/loc>.*?<\/url>)/, `$1${entries}`);
      writeIfChanged(sitemapPath, next);
    }
  };

  return {
    name: "blog-content",
    enforce: "pre",

    configResolved(config) {
      root = config.root;
      isBuild = config.command === "build";
    },

    buildStart() {
      syncManifests();
    },

    configureServer(server) {
      const onChange = (file) => {
        if (file.includes(path.normalize(contentDir)) && file.endsWith("index.md")) syncManifests();
      };
      server.watcher.on("add", onChange);
      server.watcher.on("unlink", onChange);
      server.watcher.on("change", onChange);
    },

    load(id) {
      if (!/\.md\?(meta|body)$/.test(id)) return null;
      const file = postFile(id);
      this.addWatchFile(file);
      const { meta, body } = parsePost(fs.readFileSync(file, "utf8"));

      if (id.endsWith("?body")) return `export default ${JSON.stringify(body)};`;

      const slug = path.basename(path.dirname(file));
      return `export default ${JSON.stringify({ ...meta, slug, date: String(meta.date ?? ""), ...readingTime(body) })};`;
    },
  };
}
